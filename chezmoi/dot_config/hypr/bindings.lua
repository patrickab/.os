-- Group toggle on SUPER+S instead of the default SUPER+G (replaces the
-- default scratchpad toggle).
hl.unbind("SUPER + G")
hl.unbind("SUPER + S")
o.bind("SUPER + S", "Toggle window grouping", hl.dsp.group.toggle())

-- SUPER+ALT+arrow joins the neighbor's group, or ejects if already grouped.
hl.unbind("SUPER + ALT + LEFT")
hl.unbind("SUPER + ALT + RIGHT")
hl.unbind("SUPER + ALT + UP")
hl.unbind("SUPER + ALT + DOWN")
o.bind("SUPER + ALT + LEFT", "Join group left / eject", "hypr-smart-group.sh l")
o.bind("SUPER + ALT + RIGHT", "Join group right / eject", "hypr-smart-group.sh r")
o.bind("SUPER + ALT + UP", "Join group up / eject", "hypr-smart-group.sh u")
o.bind("SUPER + ALT + DOWN", "Join group down / eject", "hypr-smart-group.sh d")

